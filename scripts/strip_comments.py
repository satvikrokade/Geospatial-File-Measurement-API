import os
import ast
import tokenize
import io

def strip_docstrings_and_comments(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        source = f.read()

    # 1. Remove comments using tokenize
    io_obj = io.StringIO(source)
    out = ""
    prev_toktype = tokenize.INDENT
    last_lineno = -1
    last_col = 0
    
    try:
        for tok in tokenize.generate_tokens(io_obj.readline):
            token_type = tok[0]
            token_string = tok[1]
            start_line, start_col = tok[2]
            end_line, end_col = tok[3]
            
            if start_line > last_lineno:
                last_col = 0
            if start_col > last_col:
                out += (" " * (start_col - last_col))
            
            if token_type == tokenize.COMMENT:
                # Skip comments
                pass
            elif token_type == tokenize.STRING:
                # Check if it's a docstring (very basic heuristic: string not part of assignment)
                # But a better way to remove docstrings is AST. For now, we'll just keep strings and use AST later.
                # Actually, AST is better for docstrings. Let's just use tokenize to remove comments first.
                out += token_string
            else:
                out += token_string
                
            last_lineno = end_line
            last_col = end_col
    except Exception as e:
        print(f"Error tokenizing {filepath}: {e}")
        return

    # Now use AST to remove docstrings if possible, or just regex.
    # It's easier to just use ast to format the code back without docstrings, but ast.unparse requires Python 3.9+
    try:
        parsed = ast.parse(out)
        for node in ast.walk(parsed):
            if not isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef, ast.Module)):
                continue
            if not len(node.body):
                continue
            if not isinstance(node.body[0], ast.Expr):
                continue
            if not hasattr(node.body[0], 'value') or not isinstance(node.body[0].value, ast.Constant):
                continue
            if isinstance(node.body[0].value.value, str):
                node.body[0].value.value = "" # Empty the docstring
        
        final_source = ast.unparse(parsed)
        
        # Clean up empty strings generated by ast.unparse
        lines = final_source.split('\n')
        final_lines = [line for line in lines if not line.strip() in ("''", '""', '""""""', "''''''")]
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write('\n'.join(final_lines) + '\n')
            
        print(f"Cleaned {filepath}")
    except Exception as e:
        print(f"Error cleaning {filepath}: {e}")

for root, dirs, files in os.walk('app'):
    for file in files:
        if file.endswith('.py'):
            strip_docstrings_and_comments(os.path.join(root, file))

for root, dirs, files in os.walk('tests'):
    for file in files:
        if file.endswith('.py'):
            strip_docstrings_and_comments(os.path.join(root, file))
